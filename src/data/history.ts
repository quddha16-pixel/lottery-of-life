import type { HistoricalHabitat, SpeciesHistory } from "../game/types";
// Conservative supported windows WITHIN species history, not claimed speciation dates.
// Sparse species-level fossil evidence gets a shorter supported window. No future births.
export const PRESENT_YEAR = 2025;
const habitat = (
  id: string,
  continent: string,
  region: string,
  landscape: string,
  temperature: number,
  from: number,
  to: number = PRESENT_YEAR,
  climate: HistoricalHabitat["climate"] = "temperate",
  hemisphere: HistoricalHabitat["hemisphere"] = "north",
  richness = 1,
): HistoricalHabitat => ({
  id,
  continent,
  region,
  place: region,
  habitat: landscape,
  temperature,
  from,
  to,
  climate,
  hemisphere,
  richness,
  precision: "regional",
});
const profile = (
  from: number,
  trophic: SpeciesHistory["trophic"],
  evidence: string,
  family: string[],
  habitats: HistoricalHabitat[],
): SpeciesHistory => ({
  existence: [from, PRESENT_YEAR],
  trophic,
  evidence,
  family,
  habitats,
});
